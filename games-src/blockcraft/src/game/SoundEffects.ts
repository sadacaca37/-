  // Duck quack sound (double harmonic nasal quack)
  public playDuckQuack() {
    try {
      this.init();
      if (!this.ctx) return;

      const osc1 = this.ctx.createOscillator();
      const osc2 = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc1.type = "sawtooth";
      osc2.type = "square";

      // Quack pitch bend: 320Hz -> 220Hz
      osc1.frequency.setValueAtTime(340, this.ctx.currentTime);
      osc1.frequency.exponentialRampToValueAtTime(240, this.ctx.currentTime + 0.16);
      osc2.frequency.setValueAtTime(450, this.ctx.currentTime);
      osc2.frequency.exponentialRampToValueAtTime(320, this.ctx.currentTime + 0.16);

      const filter = this.ctx.createBiquadFilter();
      filter.type = "bandpass";
      filter.frequency.setValueAtTime(850, this.ctx.currentTime);
      filter.Q.setValueAtTime(3.5, this.ctx.currentTime);

      gain.gain.setValueAtTime(0.18, this.ctx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.01, this.ctx.currentTime + 0.18);

      osc1.connect(filter);
      osc2.connect(filter);
      filter.connect(gain);
      gain.connect(this.ctx.destination);

      osc1.start();
      osc2.start();
      osc1.stop(this.ctx.currentTime + 0.19);
      osc2.stop(this.ctx.currentTime + 0.19);
    } catch {
      // Audio fallback
    }
  }

